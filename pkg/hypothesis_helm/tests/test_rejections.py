@pytest.fixture
def guarded_chart(tmp_path: Path) -> Chart:
    """
    Create an aggregated helper validator resembling Cassandra's TLS requirement.

    Args:
        tmp_path (Path): Isolated chart directory.

    Returns:
        Chart: Chart with valid defaults, helper-based rejection, and a conditional required field.
    """
    (tmp_path / "templates").mkdir()
    (tmp_path / "Chart.yaml").write_text(
        dedent("""
        apiVersion: v2
        name: guarded
        version: 1.0.0
    """)
    )
    defaults = {"tls": {"mode": "none", "autoGenerated": False, "secret": ""}, "name": "example", "count": 1}
    (tmp_path / "values.yaml").write_text(yamlio.dump(defaults))
    (tmp_path / "templates/_helpers.tpl").write_text(
        dedent("""
        {{- define "guarded.encryption" -}}
        {{- if ne .Values.tls.mode "none" -}}true{{- end -}}
        {{- end -}}
        {{- define "guarded.tls" -}}
        {{- if and (include "guarded.encryption" .) (not .Values.tls.autoGenerated) (not .Values.tls.secret) -}}
        TLS requires a secret or auto-generated certificates.
        {{- end -}}
        {{- end -}}
        {{- define "guarded.validate" -}}
        {{- $messages := list -}}
        {{- $messages := append $messages (include "guarded.tls" .) -}}
        {{- $messages := without $messages "" -}}
        {{- $message := join "\\n" $messages -}}
        {{- if $message -}}{{- printf "VALUES VALIDATION: %s" $message | fail -}}{{- end -}}
        {{- end -}}
    """)
    )
    (tmp_path / "templates/config.yaml").write_text(
        dedent("""
        {{- include "guarded.validate" . }}
        apiVersion: v1
        kind: ConfigMap
        metadata:
          name: {{ required "name required" .Values.name | quote }}
        data:
          mode: {{ .Values.tls.mode | quote }}
    """)
    )
    return Chart(tmp_path, {"type": "object"}, defaults)


def test_ast_call_navigation_and_cassandra_requirement(guarded_chart: Chart) -> None:
    """
    Follow helper call nodes without treating messages and comments as function calls.

    Args:
        guarded_chart (Chart): Chart with a nested validation helper graph.

    Returns:
        None: Literal words do not become sinks; helper requirements include dependent values.
    """
    assert calls(expression('printf "%s" "fail required include"')) == {"printf"}
    assert calls(expression('include "guarded.validate" .')) == {"include", "include:guarded.validate"}
    nodes = lower("{{ if false }}dead{{ else if true }}live{{ else }}other{{ end }}")
    assert [node.text for node in walk(nodes) if node.kind == "if"] == ["false", "true"]
    contracts = Contracts.build(guarded_chart.path)
    values = {**guarded_chart.defaults, "tls": {"mode": "", "autoGenerated": False, "secret": ""}}
    rejection = contracts.predict(values)
    assert rejection is not None
    assert rejection.inputs == {"$.tls.mode": "", "$.tls.autoGenerated": False, "$.tls.secret": ""}
    assert "TLS requires" in rejection.message
    assert contracts.predict(guarded_chart.defaults) is None
    cassandra = Path(__file__).resolve().parents[3] / "third_party/bitnami-charts/bitnami/cassandra"
    if cassandra.is_dir():
        defaults = mapping(yamlio.load((cassandra / "values.yaml").read_text()))
        mapping(defaults["tls"])["internodeEncryption"] = ""
        observed = Contracts.build(cassandra).predict(defaults)
        assert observed is not None and "auto-generated certificates" in observed.message
        assert observed.inputs["$.tls.autoGenerated"] is False


@pytest.mark.skipif(shutil.which("helm") is None, reason="requires Helm")
def test_native_rejection_and_dependent_generation(guarded_chart: Chart, tmp_path: Path) -> None:
    """
    Verify rejected-side witnesses and test a nearby accepted configuration with the target preserved.

    Args:
        guarded_chart (Chart): Native chart containing an explicit TLS contract.
        tmp_path (Path): Report destination.

    Returns:
        None: Filtered runs expose requirement evidence and keep accepted manifest checks active.
    """
    values = {**guarded_chart.defaults, "tls": {"mode": "", "autoGenerated": False, "secret": ""}}
    rejection = Contracts.build(guarded_chart.path).predict(values)
    assert rejection is not None
    with pytest.raises(RenderFailure) as failure:
        render(guarded_chart, values)
    assert matches_rejection(str(failure.value), rejection)
    ordinary = check_chart(guarded_chart, input_strategy=st.just(values), max_examples=1)
    assert ordinary["status"] == "failed"
    filtered = check_chart(
        guarded_chart, input_strategy=st.just(values), max_examples=1, filter_rejections=True, protected_paths=(("tls", "mode"),)
    )
    assert filtered["status"] == "passed", filtered
    evidence = mapping(filtered["configuration_rejections"])
    assert evidence["adjusted_candidates"] == 1
    assert evidence["verification_renders"] == 1
    assert filtered["attempts"] == 2  # baseline plus the accepted replacement; rejection probe is separate
    assert not filtered["coverage_complete"]
    md, _ = write_reports(
        {
            "directory": "charts",
            "started_epoch": 1,
            "elapsed_seconds": 1,
            "charts_discovered": 1,
            "counts": {"passed": 1},
            "settings": {},
            "charts": [filtered],
        },
        tmp_path / "report",
    )
    assert "Configuration rejections" in md.read_text()
    assert "TLS requires" in md.read_text()
    assert "$.tls.autoGenerated = false" in md.read_text()


