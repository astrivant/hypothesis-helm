@pytest.mark.skipif(shutil.which("helm") is None, reason="requires Helm")
def test_required_zero_false_and_opaque_guards(guarded_chart: Chart) -> None:
    """
    Match Helm required semantics and retain ordinary errors behind unsupported conditions.

    Args:
        guarded_chart (Chart): Native chart with mutable isolated template text.

    Returns:
        None: Zero and false are accepted; dynamic guards remain ordinary failing attempts.
    """
    contracts = Contracts.build(guarded_chart.path)
    for value in (0, False):
        assert contracts.predict({**guarded_chart.defaults, "name": value}) is None
        render(guarded_chart, {"name": value})
    for empty_value in ("", None):
        assert contracts.predict({**guarded_chart.defaults, "name": empty_value}) is not None
    target = guarded_chart.path / "templates/config.yaml"
    target.write_text(
        dedent("""
        {{ if eq (tpl .Values.name .) "bad" }}{{ fail "dynamic rejection" }}{{ end }}
        apiVersion: v1
        kind: ConfigMap
        metadata:
          name: safe
    """)
    )
    report = check_chart(guarded_chart, input_strategy=st.just({"name": "bad"}), max_examples=1, filter_rejections=True)
    assert report["status"] == "failed"
    assert "dynamic rejection" in str(report["error"])
    assert mapping(report["configuration_rejections"])["filtered_candidates"] == 0


@pytest.mark.skipif(shutil.which("helm") is None, reason="requires Helm")
def test_guard_filter_keeps_baseline_and_unexpected_render_errors(guarded_chart: Chart) -> None:
    """
    Keep supplied-default failures and earlier unrelated execution errors visible.

    Args:
        guarded_chart (Chart): Isolated chart with an understood TLS validation condition.

    Returns:
        None: Neither invalid defaults nor a different Helm error is silently classified as a configuration rejection.
    """
    values = {**guarded_chart.defaults, "tls": {"mode": "", "autoGenerated": False, "secret": ""}}
    invalid = Chart(guarded_chart.path, guarded_chart.schema, values)
    (guarded_chart.path / "values.yaml").write_text(yamlio.dump(values))
    result = check_chart(invalid, input_strategy=st.just(values), max_examples=1, filter_rejections=True)
    assert result["status"] == "failed"
    assert mapping(result["configuration_rejections"])["filtered_candidates"] == 0
    (guarded_chart.path / "values.yaml").write_text(yamlio.dump(guarded_chart.defaults))
    template = guarded_chart.path / "templates/config.yaml"
    original = template.read_text()
    template.write_text('{{ if ne .Values.tls.mode "none" }}{{ .Values.missing.parent }}{{ end }}\n' + original)
    result = check_chart(guarded_chart, input_strategy=st.just(values), max_examples=1, filter_rejections=True)
    assert result["status"] == "failed"
    assert "nil pointer" in str(result["error"])
    assert mapping(result["configuration_rejections"])["classifier_disagreements"] == 1
    assert mapping(result["configuration_rejections"])["filtered_candidates"] == 0
    template.write_text('{{ $_ := set .Values.tls "autoGenerated" true }}\n' + original)
    assert Contracts.build(guarded_chart.path).predict(values) is None


@pytest.mark.skipif(shutil.which("helm") is None, reason="requires Helm")
def test_finite_filters_preserve_assignments_and_counters(guarded_chart: Chart) -> None:
    """
    Exclude rejected finite assignments without repairing them into different planned cases.

    Args:
        guarded_chart (Chart): Chart with a finite invalid-only override domain and valid defaults.

    Returns:
        None: The rejection is neither a pass nor remaining unattempted work.
    """
    invalid = {**guarded_chart.defaults, "tls": {"mode": "", "autoGenerated": False, "secret": ""}}
    guarded_chart.schema = {"enum": [guarded_chart.defaults, invalid]}
    result = check_chart(guarded_chart, exhaustive=True, filter_rejections=True)
    assert result["status"] == "configuration-rejected", result
    assert mapping(result["configuration_rejections"])["adjusted_candidates"] == 0
    assert mapping(result["configuration_rejections"])["filtered_candidates"] == 1
    assert result["remaining_iterations"] == 0
    assert result["unattempted_iterations"] == 0
    assert not result["coverage_complete"]
    (guarded_chart.path / "values.schema.json").write_text(json.dumps(guarded_chart.schema))
    conflict = check_chart(guarded_chart, exhaustive=True, filter_rejections=True)
    assert conflict["status"] == "failed", conflict
    assert mapping(conflict["configuration_rejections"])["schema_conflicts"] == 1
    assert mapping(conflict["configuration_rejections"])["filtered_candidates"] == 0


@pytest.mark.skipif(shutil.which("helm") is None, reason="requires Helm")
def test_actual_cassandra_validator_with_helm(guarded_chart: Chart) -> None:
    """
    Exercise Cassandra's retained helper source through Helm with a valid dependent-field replacement.

    Args:
        guarded_chart (Chart): Isolated chart shell receiving the actual Cassandra validator.

    Returns:
        None: The original TLS mode remains selected while auto-generation satisfies Cassandra's guard.
    """
    source = Path(__file__).resolve().parents[3] / "third_party/bitnami-charts/bitnami/cassandra"
    if not source.is_dir():
        pytest.skip("Cassandra source submodule is unavailable")
    defaults = mapping(yamlio.load((source / "values.yaml").read_text()))
    (guarded_chart.path / "values.yaml").write_text(yamlio.dump(defaults))
    shutil.copyfile(source / "templates/_helpers.tpl", guarded_chart.path / "templates/_helpers.tpl")
    (guarded_chart.path / "templates/config.yaml").write_text(
        dedent("""
        {{- include "cassandra.validateValues" . }}
        apiVersion: v1
        kind: ConfigMap
        metadata:
          name: validator-witness
        data:
          mode: {{ .Values.tls.internodeEncryption | quote }}
          generated: {{ .Values.tls.autoGenerated | quote }}
    """)
    )
    chart = Chart(guarded_chart.path, {"type": "object"}, defaults)
    tls = {**mapping(defaults["tls"]), "internodeEncryption": ""}
    observed: list[dict[str, object]] = []
    report = check_chart(
        chart,
        input_strategy=st.just({**defaults, "tls": tls}),
        max_examples=1,
        filter_rejections=True,
        protected_paths=(("tls", "internodeEncryption"),),
        properties=(lambda resources: observed.extend(resources),),
    )
    assert report["status"] == "passed", report
    assert observed[-1]["data"] == {"mode": "", "generated": "true"}
    rejection = mapping(report["configuration_rejections"])
    assert rejection["verification_renders"] == 1
    assert rejection["adjusted_candidates"] == 1
